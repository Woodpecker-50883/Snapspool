import AppKit
import Foundation

enum ClipboardContent: Equatable {
    case image(data: Data, type: NSPasteboard.PasteboardType)
    case text(data: Data)
}

protocol PasteboardItemReading {
    var types: [NSPasteboard.PasteboardType] { get }
    func data(forType type: NSPasteboard.PasteboardType) -> Data?
}

extension NSPasteboardItem: PasteboardItemReading {}

@MainActor
protocol ClipboardPasteboardReading {
    var changeCount: Int { get }
    var items: [any PasteboardItemReading] { get }
}

@MainActor
struct SystemClipboardPasteboard: ClipboardPasteboardReading {
    private let pasteboard: NSPasteboard

    init(pasteboard: NSPasteboard = .general) {
        self.pasteboard = pasteboard
    }

    var changeCount: Int {
        pasteboard.changeCount
    }

    var items: [any PasteboardItemReading] {
        (pasteboard.pasteboardItems ?? []).map { $0 }
    }
}

enum ClipboardContentSelector {
    static let pngType = NSPasteboard.PasteboardType("public.png")
    static let tiffType = NSPasteboard.PasteboardType("public.tiff")
    static let jpegType = NSPasteboard.PasteboardType("public.jpeg")
    static let plainTextType = NSPasteboard.PasteboardType("public.utf8-plain-text")
    static let restoredType = NSPasteboard.PasteboardType("app.snapspool.restored")

    static let maximumTextByteCount = 1_048_576

    private static let excludedTypes: Set<NSPasteboard.PasteboardType> = [
        NSPasteboard.PasteboardType("org.nspasteboard.ConcealedType"),
        NSPasteboard.PasteboardType("org.nspasteboard.TransientType"),
        NSPasteboard.PasteboardType("org.nspasteboard.AutoGeneratedType"),
        restoredType,
    ]

    static func select(from items: [any PasteboardItemReading]) -> ClipboardContent? {
        guard let item = items.first else { return nil }
        let itemTypes = Set(item.types)
        guard itemTypes.isDisjoint(with: excludedTypes) else { return nil }

        for type in [pngType, tiffType, jpegType] where itemTypes.contains(type) {
            if let data = item.data(forType: type) {
                return .image(data: data, type: type)
            }
        }

        guard
            itemTypes.contains(plainTextType),
            let data = item.data(forType: plainTextType),
            data.count <= maximumTextByteCount
        else {
            return nil
        }

        return .text(data: data)
    }
}

@MainActor
final class ClipboardMonitor: NSObject {
    static let pollingInterval: TimeInterval = 0.3

    private let pasteboard: any ClipboardPasteboardReading
    private let didDetectContent: (ClipboardContent) -> Void
    private var lastChangeCount: Int
    private var timer: Timer?

    init(
        pasteboard: any ClipboardPasteboardReading = SystemClipboardPasteboard(),
        didDetectContent: @escaping (ClipboardContent) -> Void
    ) {
        self.pasteboard = pasteboard
        self.didDetectContent = didDetectContent
        lastChangeCount = pasteboard.changeCount
        super.init()
    }

    func start() {
        guard timer == nil else { return }
        timer = Timer.scheduledTimer(
            timeInterval: Self.pollingInterval,
            target: self,
            selector: #selector(timerDidFire),
            userInfo: nil,
            repeats: true
        )
    }

    func stop() {
        timer?.invalidate()
        timer = nil
    }

    func poll() {
        let currentChangeCount = pasteboard.changeCount
        guard currentChangeCount > lastChangeCount else { return }
        lastChangeCount = currentChangeCount

        guard let content = ClipboardContentSelector.select(from: pasteboard.items) else { return }
        didDetectContent(content)
    }

    @objc private func timerDidFire() {
        poll()
    }
}
